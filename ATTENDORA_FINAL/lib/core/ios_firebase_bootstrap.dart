import 'package:firebase_core/firebase_core.dart';

/// Placeholder Firebase configuration used **only** when the app is run against
/// the local Firebase emulators (`--dart-define=USE_FIREBASE_EMULATOR=true`) on
/// an iPhone or the iOS Simulator and no real iOS configuration has been
/// generated.
///
/// It lets someone open the project in Xcode and run it against fake data
/// without access to the real Firebase project. Nothing about it is real: the
/// emulators ignore the key, and it can never reach production because the
/// emulator flag also redirects Auth, Firestore and Storage to local ports.
///
/// The Firebase iOS SDK still checks the *shape* of what it is given, and
/// crashes at start-up (before any screen draws) if it is wrong:
///  * the app id must look like `1:<project number>:ios:<hex>` and say `ios`;
///    the hash part is documented in the SDK as "not permitted on the client so
///    the actual hash cannot be validated", so a made-up value passes. An
///    Android or web app id is rejected, since the platform must be `ios`;
///  * the API key (checked by Firebase Installations) must be exactly 39
///    characters, start with `A`, and use only letters, digits, `-` and `_`.
///    The first version of this placeholder was a shorter, readable string and
///    took the whole app down on launch - found by running it in the Simulator.
const FirebaseOptions kEmulatorOnlyIosOptions = FirebaseOptions(
  apiKey: 'AEMULATOR_ONLY_NOT_A_REAL_KEY_000000000',
  appId: '1:623151828674:ios:0000000000000000',
  messagingSenderId: '623151828674',
  // Must match the project id the sandbox data is seeded under.
  projectId: 'attendora-a0fc5',
  // Needed because sandbox start-up points Storage at its emulator, which asks
  // for a default bucket ("[firebase_storage/no-bucket]" otherwise).
  storageBucket: 'attendora-a0fc5.firebasestorage.app',
  iosBundleId: 'com.attendora.attendance',
);

/// Which options the iPhone app should start Firebase with.
///
/// * real options generated by `scripts/ios_setup.sh` always win;
/// * otherwise, in emulator mode, the placeholder above;
/// * otherwise null, which makes the app try a native GoogleService-Info.plist
///   and, failing that, show the "not connected to Firebase" screen.
FirebaseOptions? resolveIosFirebaseOptions({
  required FirebaseOptions? configured,
  required bool useEmulator,
}) => configured ?? (useEmulator ? kEmulatorOnlyIosOptions : null);
