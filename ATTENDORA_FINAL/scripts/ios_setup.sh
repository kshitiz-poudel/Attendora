#!/usr/bin/env bash
#
# Connects the iPhone app to Firebase from the GoogleService-Info.plist you
# download in the Firebase console. Run it once on a Mac, from anywhere:
#
#   scripts/ios_setup.sh ~/Downloads/GoogleService-Info.plist
#
# What it does, so nothing has to be dragged into Xcode by hand:
#   1. writes lib/firebase_options_ios.dart with the plist's values
#   2. sets the Xcode bundle identifier to the one the plist was made for
#   3. adds the Google Sign-In URL scheme and client id to Info.plist
#   4. runs `flutter pub get` and `pod install`
#
# Safe to run again (for example after downloading a fresh plist).
#
# Options:
#   --any-project     accept a plist from a different Firebase project
#   --skip-build      only edit files; do not run flutter / pod

set -euo pipefail

EXPECTED_PROJECT="attendora-a0fc5"
ANY_PROJECT=0
SKIP_BUILD=0
PLIST=""

for arg in "$@"; do
  case "$arg" in
    --any-project) ANY_PROJECT=1 ;;
    --skip-build) SKIP_BUILD=1 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) PLIST="$arg" ;;
  esac
done

die() { echo "error: $*" >&2; exit 1; }

[ "$(uname)" = "Darwin" ] || die "this script needs macOS (it uses plutil and PlistBuddy)."
[ -n "$PLIST" ] || die "pass the path to GoogleService-Info.plist. See --help."
[ -f "$PLIST" ] || die "file not found: $PLIST"
plutil -lint "$PLIST" >/dev/null || die "$PLIST is not a valid plist - download it again from the Firebase console."
[ "$(plutil -type PROJECT_ID "$PLIST" 2>/dev/null)" = "string" ] \
  || die "$PLIST does not look like a GoogleService-Info.plist (no PROJECT_ID). Download it again from the Firebase console."

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OPTIONS_DART="$ROOT/lib/firebase_options_ios.dart"
INFO_PLIST="$ROOT/ios/Runner/Info.plist"
PBXPROJ="$ROOT/ios/Runner.xcodeproj/project.pbxproj"
for f in "$INFO_PLIST" "$PBXPROJ"; do [ -f "$f" ] || die "missing $f - run this from the Attendora project."; done

# Reads one key from the plist; prints nothing if it is absent.
# plutil writes its "no value at that key path" error to *stdout*, so a plain
# `plutil ... || true` would hand that error text back as the value. Only
# print the output when plutil actually succeeded.
val() {
  local out
  if out="$(plutil -extract "$1" raw -o - "$PLIST" 2>/dev/null)"; then
    printf '%s' "$out"
  fi
}

API_KEY="$(val API_KEY)"
APP_ID="$(val GOOGLE_APP_ID)"
SENDER_ID="$(val GCM_SENDER_ID)"
PROJECT_ID="$(val PROJECT_ID)"
STORAGE_BUCKET="$(val STORAGE_BUCKET)"
BUNDLE_ID="$(val BUNDLE_ID)"
CLIENT_ID="$(val CLIENT_ID)"
REVERSED_CLIENT_ID="$(val REVERSED_CLIENT_ID)"

for pair in "API_KEY:$API_KEY" "GOOGLE_APP_ID:$APP_ID" "GCM_SENDER_ID:$SENDER_ID" \
            "PROJECT_ID:$PROJECT_ID" "BUNDLE_ID:$BUNDLE_ID"; do
  [ -n "${pair#*:}" ] || die "the plist has no ${pair%%:*}. Download GoogleService-Info.plist again."
done

# These are written into Dart source inside single quotes.
for v in "$API_KEY" "$APP_ID" "$SENDER_ID" "$PROJECT_ID" "$STORAGE_BUCKET" \
         "$BUNDLE_ID" "$CLIENT_ID"; do
  case "$v" in *"'"*|*'$'*|*'\'*) die "unexpected character in a plist value; refusing to write it into Dart." ;; esac
done

if [ "$PROJECT_ID" != "$EXPECTED_PROJECT" ] && [ "$ANY_PROJECT" -eq 0 ]; then
  die "this plist is for Firebase project '$PROJECT_ID', but the app uses '$EXPECTED_PROJECT'.
       Use the plist from the right project, or pass --any-project if this is intended."
fi

echo "Firebase project : $PROJECT_ID"
echo "iOS bundle id    : $BUNDLE_ID"

# 1. Dart options -----------------------------------------------------------
{
  echo "import 'package:firebase_core/firebase_core.dart';"
  echo
  echo "// Generated by scripts/ios_setup.sh from GoogleService-Info.plist."
  echo "// Re-run the script to regenerate. These are client identifiers, not secrets."
  echo "const FirebaseOptions iosFirebaseOptions = FirebaseOptions("
  echo "  apiKey: '$API_KEY',"
  echo "  appId: '$APP_ID',"
  echo "  messagingSenderId: '$SENDER_ID',"
  echo "  projectId: '$PROJECT_ID',"
  [ -n "$STORAGE_BUCKET" ] && echo "  storageBucket: '$STORAGE_BUCKET',"
  echo "  iosBundleId: '$BUNDLE_ID',"
  [ -n "$CLIENT_ID" ] && echo "  iosClientId: '$CLIENT_ID',"
  echo ");"
  echo
  echo "/// OAuth client id for Google Sign-In on iOS (CLIENT_ID in the plist)."
  if [ -n "$CLIENT_ID" ]; then
    echo "const String iosGoogleClientId = '$CLIENT_ID';"
  else
    echo "const String? iosGoogleClientId = null;"
  fi
} > "$OPTIONS_DART"
echo "wrote            : lib/firebase_options_ios.dart"

# 2. Xcode bundle identifier ------------------------------------------------
# Xcode signs the app under this id and Firebase only accepts the id the plist
# was created for, so they must match.
CURRENT_ID="$(grep -E 'PRODUCT_BUNDLE_IDENTIFIER = ' "$PBXPROJ" | grep -v RunnerTests \
  | head -1 | sed -E 's/.*= ([^;]+);.*/\1/')"
if [ -n "$CURRENT_ID" ] && [ "$CURRENT_ID" != "$BUNDLE_ID" ]; then
  # Exact-match replacement; the tests target keeps its ".RunnerTests" suffix.
  sed -i '' \
    -e "s/PRODUCT_BUNDLE_IDENTIFIER = ${CURRENT_ID//./\\.}\.RunnerTests;/PRODUCT_BUNDLE_IDENTIFIER = ${BUNDLE_ID}.RunnerTests;/" \
    -e "s/PRODUCT_BUNDLE_IDENTIFIER = ${CURRENT_ID//./\\.};/PRODUCT_BUNDLE_IDENTIFIER = ${BUNDLE_ID};/" \
    "$PBXPROJ"
  echo "xcode bundle id  : $CURRENT_ID -> $BUNDLE_ID"
else
  echo "xcode bundle id  : already $BUNDLE_ID"
fi

# 3. Google Sign-In ---------------------------------------------------------
PB=/usr/libexec/PlistBuddy
"$PB" -c "Delete :CFBundleURLTypes" "$INFO_PLIST" >/dev/null 2>&1 || true
"$PB" -c "Delete :GIDClientID" "$INFO_PLIST" >/dev/null 2>&1 || true
if [ -n "$REVERSED_CLIENT_ID" ] && [ -n "$CLIENT_ID" ]; then
  "$PB" -c "Add :CFBundleURLTypes array" "$INFO_PLIST"
  "$PB" -c "Add :CFBundleURLTypes:0 dict" "$INFO_PLIST"
  "$PB" -c "Add :CFBundleURLTypes:0:CFBundleTypeRole string Editor" "$INFO_PLIST"
  "$PB" -c "Add :CFBundleURLTypes:0:CFBundleURLSchemes array" "$INFO_PLIST"
  "$PB" -c "Add :CFBundleURLTypes:0:CFBundleURLSchemes:0 string $REVERSED_CLIENT_ID" "$INFO_PLIST"
  "$PB" -c "Add :GIDClientID string $CLIENT_ID" "$INFO_PLIST"
  echo "google sign-in   : URL scheme and client id added to Info.plist"
else
  echo "google sign-in   : NOT configured - this plist has no CLIENT_ID."
  echo "                   In Firebase console > Authentication > Sign-in method,"
  echo "                   make sure Google is enabled, then download the plist again"
  echo "                   and re-run this script. (ID-number login works regardless.)"
fi
plutil -lint "$INFO_PLIST" >/dev/null || die "Info.plist ended up invalid; restore it with git checkout ios/Runner/Info.plist"

# 4. Dependencies -----------------------------------------------------------
if [ "$SKIP_BUILD" -eq 1 ]; then
  echo "skipped          : flutter pub get / pod install (--skip-build)"
else
  command -v flutter >/dev/null || die "flutter is not on your PATH."
  ( cd "$ROOT" && flutter pub get )
  if command -v pod >/dev/null; then
    ( cd "$ROOT/ios" && pod install )
  else
    echo "CocoaPods is not installed. Install it with:  brew install cocoapods"
    echo "then run:  cd ios && pod install"
  fi
fi

cat <<EOF

Done. Next:
  1. open ios/Runner.xcworkspace in Xcode
  2. Runner > Signing & Capabilities > pick your Team (your Apple ID)
  3. plug in the iPhone, trust the computer, then:  flutter run
See IOS_FIREBASE_SETUP.md for the full walk-through.
EOF
